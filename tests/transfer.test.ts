import { describe, expect, test } from "vitest";
import {
  buildGuardedExportAudit,
  buildRawEvidenceSession,
  mappingStageGate,
  promoteMapping,
  validateRoundTrip,
} from "../src/bridge/guardedTransfer";
import { createDefaultBridgeMappings } from "../src/bridge/model";
import type { RawEvidenceSession } from "../src/bridge/types";
import { createPlannedSegment, createPlannedShow } from "../src/planner/model";
import type { TewResearchSnapshot, TewSnapshot } from "../src/tew/types";
import { buildTransferPackage, buildTransferText, synchronizeTransferRecord } from "../src/transfer/model";

